OUT = pathlib.Path(__file__).resolve().parents[2] / "SevenDashesToDie" / "Config" / "Localization.csv"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        writer.writerow(HEADER)
        for key, (file_col, type_col, main_menu, texts) in ENTRIES.items():
            english = texts["english"]
            row = [key, file_col, type_col, main_menu, "", "", english, ""]
            row += [texts.get(lang, english) for lang in LANGUAGES]
            writer.writerow(row)
    print(f"wrote {OUT} ({len(ENTRIES)} keys, {len(LANGUAGES)} languages)")


if __name__ == "__main__":
    main()
